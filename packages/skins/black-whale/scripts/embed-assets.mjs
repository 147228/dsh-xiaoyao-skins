import { readFile, writeFile } from 'node:fs/promises'
import { extname, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const entries = [
  ['BLACK_WHALE_LAB', 'assets/black-whale-lab.webp'],
  ['DSH_BLACK_WHALE', 'assets/dsh-black-whale.png'],
]
const mime = (file) => extname(file) === '.webp' ? 'image/webp' : 'image/png'
const lines = ['// Generated by scripts/embed-assets.mjs. Do not edit by hand.']
for (const [name, file] of entries) {
  const payload = await readFile(resolve(root, file), 'base64')
  lines.push(`export const ${name} = 'data:${mime(file)};base64,${payload}'`)
}
await writeFile(resolve(root, 'src/client/art.generated.ts'), `${lines.join('\n')}\n`)
