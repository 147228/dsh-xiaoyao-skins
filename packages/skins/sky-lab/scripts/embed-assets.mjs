import { readFile, writeFile } from 'node:fs/promises'
import { extname, resolve } from 'node:path'
const root = resolve(import.meta.dirname, '..')
const entries = [['SKY_STAGE','assets/sky-lab-stage.webp'],['SKY_DUO','assets/sky-lab-duo.png'],['SKY_EMBLEM','assets/sky-lab-emblem.png']]
const lines = ['// Generated by scripts/embed-assets.mjs. Do not edit.']
for (const [name,file] of entries) {
  const type = extname(file) === '.webp' ? 'image/webp' : 'image/png'
  lines.push(`export const ${name} = 'data:${type};base64,${await readFile(resolve(root,file),'base64')}'`)
}
await writeFile(resolve(root,'src/client/art.generated.ts'), `${lines.join('\n')}\n`)
